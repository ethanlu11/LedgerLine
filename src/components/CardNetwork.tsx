function VisaMark({ height }: { height: number }) {
  return (
    <svg
      viewBox="0 0 960 312"
      height={height}
      style={{ width: (height * 960) / 312 }}
      role="img"
      aria-label="Visa"
      className="shrink-0"
    >
      <path d={VISA_PATH} fill="currentColor" fillRule="evenodd" />
    </svg>
  );
}

export function CardNetworkMark({
  network,
  height = 20,
}: {
  network: CardNetwork;
  /** Nominal height; each mark is scaled so the two carry the same visual weight. */
  height?: number;
}) {
  // The wordmark's cap height is well under its font size, so the discs need
  // trimming to match it optically.
  return network === "mastercard" ? (
    <MastercardMark height={height * 1.34} />
  ) : (
    <VisaMark height={height * 0.72} />
  );
}
