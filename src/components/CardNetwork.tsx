export type CardNetwork = "visa" | "mastercard";

export function parseNetwork(value: string | null | undefined): CardNetwork {
  return value === "mastercard" ? "mastercard" : "visa";
}

export const NETWORK_LABEL: Record<CardNetwork, string> = {
  visa: "Visa",
  mastercard: "Mastercard",
};

/** Mastercard's two interlocking discs, with the overlap drawn as its own shape. */
function MastercardMark({ height }: { height: number }) {
  return (
    <svg
      viewBox="0 0 48 30"
      height={height}
      role="img"
      aria-label="Mastercard"
      style={{ width: (height * 48) / 30 }}
    >
      <defs>
        <clipPath id="mc-left-disc">
          <circle cx="18" cy="15" r="11" />
        </clipPath>
      </defs>
      <circle cx="18" cy="15" r="11" fill="#EB001B" />
      <circle cx="30" cy="15" r="11" fill="#F79E1B" />
      {/* The lens where the discs meet. */}
      <circle cx="30" cy="15" r="11" fill="#FF5F00" clipPath="url(#mc-left-disc)" />
    </svg>
  );
}

